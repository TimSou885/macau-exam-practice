/**
 * Generates migrations/seed.sql from question-banks/*.js
 * Run: node scripts/generate-seed-sql.mjs
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { getAllQuestionsForSeed } from '../question-banks/index.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'scripts/seed.sql')

function sqlEscape(value) {
  if (value == null) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

const questions = getAllQuestionsForSeed()
const lines = [
  '-- Auto-generated by scripts/generate-seed-sql.mjs; do not edit manually.',
  'DELETE FROM questions;',
]

for (const q of questions) {
  const options = JSON.stringify(q.options)
  const examTypes = JSON.stringify(q.examTypes)
  const explanation = q.explanation != null ? sqlEscape(q.explanation) : 'NULL'
  lines.push(
    `INSERT INTO questions (id, category, question, options, correct_key, explanation, exam_types) VALUES (${sqlEscape(q.id)}, ${sqlEscape(q.category)}, ${sqlEscape(q.question)}, ${sqlEscape(options)}, ${sqlEscape(q.correctKey)}, ${explanation}, ${sqlEscape(examTypes)});`
  )
}

writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf8')
console.log(`Wrote ${questions.length} questions to ${outPath}`)
