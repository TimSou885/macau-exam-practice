// Builds worker/fixtures/spa-shell.generated.ts from root index.html for Worker-runtime SEO tests.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'

const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8')
const out = new URL('../worker/fixtures/spa-shell.generated.ts', import.meta.url)
mkdirSync(new URL('../worker/fixtures', import.meta.url), { recursive: true })
const body = `// Auto-generated by scripts/gen-shell-fixture.mjs — do not edit.\nexport const SHELL_HTML = ${JSON.stringify(html)}\n`
writeFileSync(out, body)
console.log('Wrote', out.pathname || out.href)
